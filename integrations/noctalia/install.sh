#!/usr/bin/env bash
# Install the Noctalia Shell -> Caelestia-DNT theme bridge.
#
# This registers two Noctalia user templates:
#   1. the extension theme snapshot (noctalia-theme.json + wallpaper)
#   2. an optional Thorium/Chromium browser-chrome theme
#
# Usage:
#   ./integrations/noctalia/install.sh [--extension-dir DIR] [--no-apply]
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_dir="$(cd -- "$script_dir/../.." && pwd)"
extension_dir="${CAELESTIA_DNT_DIR:-$repo_dir}"

apply_now=1
while [[ $# -gt 0 ]]; do
  case "$1" in
    --extension-dir)
      extension_dir="${2:?--extension-dir needs a value}"
      shift 2
      ;;
    --no-apply)
      apply_now=0
      shift
      ;;
    -h|--help)
      sed -n '2,14p' "${BASH_SOURCE[0]}"
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      exit 2
      ;;
  esac
done

extension_dir="$(cd -- "$extension_dir" && pwd)"
config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
cache_home="${XDG_CACHE_HOME:-$HOME/.cache}"
noctalia_dir="$config_home/noctalia"
config_file="$noctalia_dir/noctalia-dnt.toml"
thorium_dir="$cache_home/noctalia-dnt/thorium-theme"

mkdir -p "$noctalia_dir" "$thorium_dir"

toml_escape() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

if [[ -f "$config_file" ]]; then
  backup="$config_file.bak.$(date +%Y%m%d-%H%M%S)"
  cp -a -- "$config_file" "$backup"
  echo "Backed up existing Noctalia config to $backup"
fi

cat >"$config_file" <<EOF
# Generated by Caelestia-DNT (integrations/noctalia/install.sh).
# Remove this file or run integrations/noctalia/uninstall.sh to disable.

[theme.templates.user.noctalia_dnt]
input_path  = "$(toml_escape "$script_dir/theme.json.tpl")"
output_path = "$(toml_escape "$extension_dir/noctalia-theme.json")"
post_hook   = "bash \"$(toml_escape "$script_dir/sync-wallpaper.sh")\" \"{{ image }}\""
hook_async  = false

[theme.templates.user.noctalia_dnt_browser]
input_path  = "$(toml_escape "$script_dir/thorium-theme.json.tpl")"
output_path = "$(toml_escape "$thorium_dir/manifest.json")"
post_hook   = "bash \"$(toml_escape "$script_dir/thorium-theme.sh")\""
hook_async  = false
EOF

chmod +x "$script_dir/sync-wallpaper.sh" "$script_dir/thorium-theme.sh"

echo "Noctalia template config: $config_file"
echo "Extension directory:      $extension_dir"
echo "Browser theme directory:  $thorium_dir"

if ! command -v noctalia >/dev/null 2>&1; then
  echo "Warning: noctalia CLI not found; apply the templates from Noctalia Settings → Templates." >&2
  exit 0
fi

# Copy the current wallpaper immediately, even before the first palette change.
if wallpaper="$(noctalia msg wallpaper-get 2>/dev/null)" && [[ -n "$wallpaper" ]]; then
  CAELESTIA_DNT_DIR="$extension_dir" bash "$script_dir/sync-wallpaper.sh" "$wallpaper" || true
fi

if [[ "$apply_now" -eq 1 ]]; then
  if noctalia msg templates-apply >/dev/null 2>&1; then
    echo "Applied Noctalia templates."
  else
    echo "Could not apply templates automatically. Run: noctalia msg templates-apply" >&2
  fi
fi

if [[ ! -f "$extension_dir/noctalia-theme.json" ]]; then
  echo "Warning: $extension_dir/noctalia-theme.json was not generated yet." >&2
  echo "Open Noctalia Settings → Templates and apply the Noctalia-DNT templates." >&2
fi

cat <<EOF

Next steps
  1. Open Thorium → chrome://extensions → Developer mode → Load unpacked
     and select: $extension_dir
  2. Optional browser chrome theme (tab strip / toolbar / frame):
     chrome://extensions → Load unpacked → $thorium_dir
  3. Verify the live palette with:
     noctalia msg templates-apply
EOF
